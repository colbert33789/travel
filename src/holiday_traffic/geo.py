def road_distance(town: Town) -> tuple[float, float]:
    """深圳出发的 (实际自驾里程 km, 平日耗时 h); 缺实测值时由球面距离折算."""
    if town.name in ROAD_MEASURED:
        return ROAD_MEASURED[town.name]
    km = distance_shenzhen(town) * 1.3
    return km, km / FALLBACK_KMH


# 单用会产生歧义的短名覆盖表: 括号内容是「特征」而非地名时, 必须补地域前缀,
# 否则读者看到「美食 78% · 10/4」无从得知是哪里。
SHORT_OVERRIDES = {"地下河": "连州地下河", "大峡谷": "乳源大峡谷", "碉楼": "开平碉楼",
                   "客都": "梅县客都", "禅泉": "新兴禅泉", "美食": "顺德美食"}


def short_name(name: str) -> str:
    """图表/文案用短名: 取括号内景点名; 歧义加地域前缀(如 番禺长隆/横琴长隆)."""
    if "(" not in name:
        return name
    before, inner = name.split("(", 1)
    inner = inner.rstrip(")")
    if inner in SHORT_OVERRIDES:
        return SHORT_OVERRIDES[inner]
    dup = sum(1 for t in TOWNS if t.name.split("(")[-1].rstrip(")") == inner) > 1
    return f"{before[-2:]}{inner}" if dup else inner


def distance_shenzhen(town: Town) -> float:
    """深圳中心城区(114.06, 22.55)到目标城镇的球面距离(km)."""
    from math import asin, cos, radians, sin, sqrt

    lat1, lon1 = radians(22.55), radians(114.06)
    lat2, lon2 = radians(town.lat), radians(town.lon)
    dlat, dlon = lat2 - lat1, lon2 - lon1
    a = sin(dlat / 2) ** 2 + cos(lat1) * cos(lat2) * sin(dlon / 2) ** 2
    return 2 * 6371.0 * asin(sqrt(a))
