# 实测长途(>=150km, 24 个样本)合计 6919km / 87.0h -> 含两端市区段的综合均速 79.5km/h,
# 明显低于原先假设的 95km/h。缺实测值时用该值由里程折算。
FALLBACK_KMH = 79.5
# 平日全天拥堵延时指数均值(高德口径): 实测耗时含平日拥堵, 需先反推自由流耗时
